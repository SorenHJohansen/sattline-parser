"""Typed builtin function registry, built from ``catalogue.json``.

The catalogue is generated by ``scripts/gen_builtin_catalogue.py`` and shipped
as package data. This module turns it into immutable value objects and answers
name lookups. Function names are case-insensitive and use the same identifier
folding as the rest of the language.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Final, Literal, cast

from sattline_parser.validation.names import fold_identifier

BuiltinKind = Literal["function", "procedure"]
BuiltinDirection = Literal["in", "in var", "out", "inout"]
BuiltinSorting = Literal["RS", "WS", "RS/WS", "NoS"]
BuiltinOwnership = Literal["RO", "WO", "RO/WO", "NoO"]

_CATALOGUE_PATH: Final[Path] = Path(__file__).with_name("catalogue.json")


@dataclass(frozen=True, slots=True)
class BuiltinParameter:
    """One documented parameter of a builtin call."""

    name: str
    datatype: str
    direction: BuiltinDirection
    sorting: BuiltinSorting
    ownership: BuiltinOwnership


@dataclass(frozen=True, slots=True)
class BuiltinFunction:
    """A documented builtin function or procedure signature.

    ``typed`` is false for a name the catalogue carries without a full
    transcribed parameter list; such an entry still has an arity (the number of
    documented parameters) and can be arity-checked.
    """

    name: str
    kind: BuiltinKind
    return_type: str | None
    precision_scangroup: bool
    typed: bool
    parameters: tuple[BuiltinParameter, ...]

    @property
    def arity(self) -> int:
        """Number of documented parameters."""
        return len(self.parameters)

    @property
    def out_arg_positions(self) -> frozenset[int]:
        """1-based positions documented as written by the call (``out`` / ``inout``)."""
        return frozenset(
            position
            for position, parameter in enumerate(self.parameters, start=1)
            if parameter.direction in {"out", "inout"}
        )


def _parse_parameter(raw: object) -> BuiltinParameter:
    entry = cast("dict[str, object]", raw)
    return BuiltinParameter(
        name=cast("str", entry["name"]),
        datatype=cast("str", entry["datatype"]),
        direction=cast("BuiltinDirection", entry["direction"]),
        sorting=cast("BuiltinSorting", entry["sorting"]),
        ownership=cast("BuiltinOwnership", entry["ownership"]),
    )


def _parse_function(name: str, raw: object) -> BuiltinFunction:
    entry = cast("dict[str, object]", raw)
    parameters = cast("list[object]", entry["parameters"])
    return BuiltinFunction(
        name=name,
        kind=cast("BuiltinKind", entry["kind"]),
        return_type=cast("str | None", entry["return_type"]),
        precision_scangroup=cast("bool", entry["precision_scangroup"]),
        typed=cast("bool", entry["typed"]),
        parameters=tuple(_parse_parameter(parameter) for parameter in parameters),
    )


def _load_catalogue() -> tuple[dict[str, BuiltinFunction], dict[str, str], dict[str, object]]:
    document = cast("dict[str, object]", json.loads(_CATALOGUE_PATH.read_text(encoding="utf-8")))
    functions = cast("dict[str, object]", document["functions"])
    meta = cast("dict[str, object]", document["meta"])
    aliases = cast("dict[str, str]", meta.get("aliases", {}))
    parsed = {name: _parse_function(name, raw) for name, raw in functions.items()}
    return parsed, dict(aliases), meta


#: Canonical (casefolded) name -> signature, aliases, and catalogue metadata.
BUILTIN_FUNCTIONS, BUILTIN_ALIASES, CATALOGUE_META = _load_catalogue()

_FOLDED_FUNCTIONS: Final[dict[str, BuiltinFunction]] = {
    fold_identifier(name): signature for name, signature in BUILTIN_FUNCTIONS.items()
}
_FOLDED_ALIASES: Final[dict[str, BuiltinFunction]] = {
    fold_identifier(alias): BUILTIN_FUNCTIONS[target] for alias, target in BUILTIN_ALIASES.items()
}


def get_function_signature(name: str) -> BuiltinFunction | None:
    """Return the documented signature for ``name``, or ``None`` when unknown."""
    key = fold_identifier(name)
    signature = _FOLDED_FUNCTIONS.get(key)
    if signature is not None:
        return signature
    return _FOLDED_ALIASES.get(key)


def is_builtin_function(name: str) -> bool:
    """Return whether ``name`` is a documented builtin (including aliases)."""
    key = fold_identifier(name)
    return key in _FOLDED_FUNCTIONS or key in _FOLDED_ALIASES


