"""Golden validation manifest for the parser corpus.

The manifest is generated by ``scripts/export_parity_expectations.py``. It
records the code, severity, and span of every diagnostic for every fixture, so
a rule change is visible as a manifest diff rather than a silent pass.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from sattline_parser.api import parse_source_file
from sattline_parser.validation import validate_basepicture

_ROOT = Path(__file__).resolve().parents[2]
_CORPUS = _ROOT / "tests" / "fixtures" / "corpus"
_EXPECTATIONS = _ROOT / "tests" / "fixtures" / "validation" / "expectations.json"


def _manifest() -> dict[str, list[dict[str, object]]]:
    document = json.loads(_EXPECTATIONS.read_text(encoding="utf-8"))
    return document["fixtures"]


def _actual(path: Path) -> list[dict[str, object]]:
    bp = parse_source_file(path, log_failures=False)
    records: list[dict[str, object]] = []
    for diagnostic in validate_basepicture(bp):
        span = diagnostic.span
        records.append(
            {
                "code": diagnostic.code.value,
                "severity": diagnostic.severity.value,
                "line": None if span is None else span.line,
                "column": None if span is None else span.column,
                "length": None if span is None else max(span.end - span.start, 0),
            }
        )
    return records


def test_manifest_covers_every_corpus_fixture() -> None:
    manifest = _manifest()
    corpus = {
        f"{group}/{path.name}" for group in ("invalid", "valid", "edge_cases") for path in (_CORPUS / group).glob("*.s")
    }
    assert set(manifest) == corpus


@pytest.mark.parametrize("fixture", sorted(_manifest()))
def test_fixture_matches_the_manifest(fixture: str) -> None:
    expected = _manifest()[fixture]
    path = _CORPUS / fixture
    if expected and "parse_error" in expected[0]:
        with pytest.raises(Exception):  # noqa: B017 - the manifest only records that parsing failed
            parse_source_file(path, log_failures=False)
        return
    assert _actual(path) == expected
